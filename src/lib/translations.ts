/**
 * Checks if a category supports language switching.
 * Strictly limited to Private Job Resume and Marriage Biodata per user specifications.
 */
export function isLanguageSupported(category: DocumentCategory): boolean {
  return category === 'private_job_resume' || category === 'marriage_biodata';
}

/**
 * Translates a given label/heading key into the target language.
 * Falls back to English if the key or language is missing.
 */
export function t(key: string, lang?: IndianResumeLanguage): string {
  const activeLang = lang || 'en';
  if (!TRANSLATIONS[key]) {
    return key;
  }
  return TRANSLATIONS[key][activeLang] || TRANSLATIONS[key]['en'] || key;
}

/**
 * Translates common standard values (e.g. 'Vegetarian', 'Fair', 'Unmarried', 'Male', 'Indian').
 * If the value has no mapping or is already translated, returns the value as is.
 */
export function translateValue(val?: string, lang?: IndianResumeLanguage): string {
  if (!val || !val.trim()) return '';
  const activeLang = lang || 'en';
  if (activeLang === 'en') return val;

  const trimmed = val.trim();
  if (VALUE_TRANSLATIONS[trimmed] && VALUE_TRANSLATIONS[trimmed][activeLang]) {
    return VALUE_TRANSLATIONS[trimmed][activeLang];
  }

  // Check if string contains standard phrase in English and translate that piece
  for (const [engWord, dict] of Object.entries(VALUE_TRANSLATIONS)) {
    if (dict[activeLang] && trimmed.toLowerCase() === engWord.toLowerCase()) {
      return dict[activeLang];
    }
  }

  return val;
}

/**
 * Returns standard legal declaration text for the selected language.
 */
export function getDefaultDeclarationText(lang?: IndianResumeLanguage): string {
  return t('declarationText', lang);
}

/**
 * Checks whether the given declaration text matches any default declaration template.
 */
export function isDefaultDeclaration(text?: string): boolean {
  if (!text) return true;
  const trimmed = text.trim();
  return Object.values(TRANSLATIONS['declarationText']).some(
    (decl) => decl.trim() === trimmed
  );
}

/**
 * Checks if the language is right-to-left (Urdu).
 */
export function isRTL(lang?: IndianResumeLanguage): boolean {
  return lang === 'ur';
}

